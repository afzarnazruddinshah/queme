import { redis } from '../../lib/redis';
import { getQueueKeys } from '../../lib/redisKeys';

export default async function handler(req, res) {
  const VERIFY_TOKEN = process.env.META_VERIFY_TOKEN;
  const ACCESS_TOKEN = process.env.WHATSAPP_ACCESS_TOKEN;
  const PHONE_NUMBER_ID = process.env.WHATSAPP_PHONE_NUMBER_ID;

  // 1. Meta Webhook Verification (GET)
  if (req.method === 'GET') {
    const mode = req.query['hub.mode'];
    const token = req.query['hub.verify_token'];
    const challenge = req.query['hub.challenge'];

    if (mode === 'subscribe' && token === VERIFY_TOKEN) {
      return res.status(200).send(challenge);
    }
    return res.status(403).send('Forbidden');
  }

  // 2. Incoming Messages Handler (POST)
  if (req.method === 'POST') {
    const body = req.body;

    if (body.object && body.entry) {
      const entryValue = body.entry[0]?.changes?.[0]?.value;
      const messages = entryValue?.messages;

      if (messages && messages[0]) {
        const message = messages[0];
        const from = message.from;

        if (message.type === 'text') {
          const userName = message.text.body.trim();

          // 1. Extract dynamic metadata from Meta payload
          const metadata = entryValue?.metadata;
          const incomingPhoneId = metadata?.phone_number_id || PHONE_NUMBER_ID;
          const displayPhoneNumber = metadata?.display_phone_number;

          // 2. Resolve tenantId dynamically from Redis
          let tenantId = null;
          if (incomingPhoneId) {
            tenantId = await redis.get(`phone:${incomingPhoneId}:tenant`);
          }
          if (!tenantId && displayPhoneNumber) {
            tenantId = await redis.get(`phone:${displayPhoneNumber}:tenant`);
          }

          // Fallback if key is not yet set in Upstash
          if (!tenantId) {
            tenantId = 'neefa';
          }

          // 3. Derive multi-tenant keys
          const keys = getQueueKeys(tenantId);

          // 4. Increment counter & queue the token
          let tokenNumber = 'A001';
          try {
            const tokenCounter = await redis.incr(keys.counter);
            tokenNumber = `A${String(tokenCounter).padStart(3, '0')}`;

const patientName =
  entryValue?.contacts?.[0]?.profile?.name ||
  message.text?.body?.trim() ||
  'WhatsApp Patient';
            const tokenData = {
              tokenNumber,
              patientName: patientName,
              phoneNumber: from || message.from || '—',
              source: 'whatsapp',
              createdAt: new Date().toISOString(),
              status: 'waiting',
            };

            await redis.rpush(keys.queue, JSON.stringify(tokenData));
          } catch (redisErr) {
            console.error('Redis token creation error:', redisErr);
          }

          // 5. Send confirmation message back to WhatsApp
          const replyText = `Hi ${userName}! Your token number is ${tokenNumber}. Please wait for your turn.`;
          const targetPhoneId = incomingPhoneId || PHONE_NUMBER_ID;

          try {
            await fetch(`https://graph.facebook.com/v21.0/${targetPhoneId}/messages`, {
              method: 'POST',
              headers: {
                Authorization: `Bearer ${ACCESS_TOKEN}`,
                'Content-Type': 'application/json',
              },
              body: JSON.stringify({
                messaging_product: 'whatsapp',
                recipient_type: 'individual',
                to: from,
                type: 'text',
                text: { body: replyText },
              }),
            });
          } catch (err) {
            console.error('Fetch error:', err);
          }
        }
      }
    }
    return res.status(200).json({ status: 'ok' });
  }

  return res.status(405).send('Method Not Allowed');
}
